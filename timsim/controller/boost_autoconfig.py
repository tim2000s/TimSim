"""Deriving a Boost V5 configuration for one subject from its own dosing history.

The algorithm's dose calibration is co-adapted with the person running it, so its own onboarding
path does not start a new user on cohort defaults. `BoostV5AutoConfig` in the AAPS tree takes the
user's last fourteen days of V1 dosing and glycaemia and derives every knob from it, easing
aggression down for a hypoglycaemia-prone history and sizing the dose caps from the doses that
person already gives themselves. This is a port of that function, constant for constant, so a
simulated subject is configured the way a real user would be rather than at a default nobody
runs.

Running Boost here at the factory defaults understated it in a way that is now measurable: the
committed cap of 0.25 U and confirmed cap of 1.0 U bound on 74.3 and 60.2 per cent of their own
cycles, and the arm lost ten of nineteen subjects, six of them to hyperglycaemia.

The mapping from a real user's history to a simulated subject's is the one modelling choice
here. A real profile comes from that person running the previous version of the algorithm; a
subject has no such history, so it is generated by running the reference correction loop for the
same fourteen days. Its meal boluses stand in for the manual boluses and its corrections for the
microboluses, which is what those two streams are in each case. The alternative, running the
algorithm under test to configure itself, is circular.

Source: plugins/aps/src/main/kotlin/app/aaps/plugins/aps/openAPSBoostV5/BoostV5AutoConfig.kt on
the dev branch of Boost-in-AAPS_3.4.
"""
from dataclasses import dataclass, field

import numpy as np

# Below either of these there is not enough history to configure responsibly, and the source
# returns nothing rather than guessing.
MIN_DAYS = 7
MIN_BG_READINGS = 1500

# Consensus targets, and the cut-points above which the history counts as hypoglycaemia-prone.
TBR70_TARGET = 4.0
SEV54_TARGET = 1.0
SEV54_HYPO_PRONE = 1.5
TBR70_HYPO_PRONE = 6.0

# Tighter cut-points that gate the two switches which add insulin.
WELL_CONTROLLED_MAX_TBR70 = 1.5
WELL_CONTROLLED_MAX_SEV54 = 0.3

LOOKBACK_DAYS = 14

# A percentile of four manual boluses is noise rather than a dose habit, so the manual stream
# only participates in the confirmed cap with a sample this size or larger.
MIN_MANUAL_BOLUS_SAMPLES = 10
CUMULATIVE_CAP_MAX_U = 10.0


@dataclass
class V1Profile:
    """What the plugin gathers from a user's last fourteen days, and its simulated counterpart."""
    days_with_data: int
    bg_reading_count: int
    tdd_median_u: float
    manual_boluses_u: list
    smb_amounts_u: list
    tbr_below_70_pct: float
    time_below_54_pct: float
    mean_glucose_mgdl: float
    current_max_iob_u: float
    current_max_bolus_u: float


@dataclass
class V5Suggestion:
    aggression: float
    hypo_caution: float
    confirmed_cap_u: float
    committed_cap_u: float
    cumulative_smb_cap_60min_u: float
    max_iob_u: float
    bolus_cap_u: float
    fast_carb_confirm: bool
    aggressive_early_confirm: bool
    velocity_budget_floor: bool
    primer_cap_u: float
    primer_tbr_fallback: bool
    rationale: list = field(default_factory=list)


def percentile(values, p):
    """The source's linear-interpolated percentile over positive finite values."""
    v = sorted(x for x in values if np.isfinite(x) and x > 0.0)
    if not v:
        return 0.0
    if len(v) == 1:
        return float(v[0])
    rank = (p / 100.0) * (len(v) - 1)
    lo = int(rank)
    hi = min(lo + 1, len(v) - 1)
    return float(v[lo] + (v[hi] - v[lo]) * (rank - lo))


def cumulative_cap_60min(confirmed_cap_u, committed_cap_u):
    """One confirm shot plus two holds an hour, which bounds frequency where the per-shot caps
    bound magnitude."""
    return round(min(max(confirmed_cap_u + 2.0 * committed_cap_u, 1.0), CUMULATIVE_CAP_MAX_U), 1)


def compute(p):
    """The suggested configuration, or None when the history is too thin to configure on."""
    if p.days_with_data < MIN_DAYS or p.bg_reading_count < MIN_BG_READINGS:
        return None

    reasons = []
    hypo_prone = (p.time_below_54_pct > SEV54_HYPO_PRONE
                  or p.tbr_below_70_pct > TBR70_HYPO_PRONE)

    caution = 1.0 + max(0.0, p.tbr_below_70_pct - TBR70_TARGET) / 4.0 \
                  + max(0.0, p.time_below_54_pct - SEV54_TARGET) * 0.5
    hypo_caution = round(min(max(caution, 1.0), 2.0), 1)
    reasons.append(f"hypo caution {hypo_caution} from time below 70 of "
                   f"{p.tbr_below_70_pct:.1f}% and below 54 of {p.time_below_54_pct:.1f}%")

    # Never raised above neutral. The source only eases it down for a hypoglycaemic history,
    # because raising it is the direction that adds insulin.
    aggression = 0.85 if hypo_prone else (0.92 if p.tbr_below_70_pct > TBR70_TARGET else 1.0)
    reasons.append(f"aggression {aggression}")

    manual_p90 = (percentile(p.manual_boluses_u, 90.0)
                  if len(p.manual_boluses_u) >= MIN_MANUAL_BOLUS_SAMPLES else 0.0)
    confirmed = round(min(max(max(manual_p90, percentile(p.smb_amounts_u, 95.0)), 1.5), 7.5), 2)
    committed = round(min(max(max(percentile(p.smb_amounts_u, 75.0),
                                  p.tdd_median_u / 40.0), 0.25), 2.5), 2)
    reasons.append(f"confirmed cap {confirmed} U, committed cap {committed} U")

    well_controlled = (p.tbr_below_70_pct < WELL_CONTROLLED_MAX_TBR70
                       and p.time_below_54_pct < WELL_CONTROLLED_MAX_SEV54)
    primer_frac = 0.25 if hypo_prone else (0.5 if well_controlled else 0.4)

    return V5Suggestion(
        aggression=aggression, hypo_caution=hypo_caution,
        confirmed_cap_u=confirmed, committed_cap_u=committed,
        cumulative_smb_cap_60min_u=cumulative_cap_60min(confirmed, committed),
        max_iob_u=round(min(max(p.current_max_iob_u, 0.1), 12.0), 1),
        bolus_cap_u=round(min(max(p.current_max_bolus_u, 0.1), 10.0), 1),
        fast_carb_confirm=not hypo_prone,
        aggressive_early_confirm=well_controlled,
        velocity_budget_floor=well_controlled,
        primer_cap_u=round(min(max(committed * primer_frac, 0.0), 0.6), 2),
        primer_tbr_fallback=not well_controlled,
        rationale=reasons)


__all__ = ["V1Profile", "V5Suggestion", "compute", "percentile", "cumulative_cap_60min",
           "MIN_DAYS", "MIN_BG_READINGS", "LOOKBACK_DAYS", "MIN_MANUAL_BOLUS_SAMPLES",
           "SEV54_HYPO_PRONE", "TBR70_HYPO_PRONE", "WELL_CONTROLLED_MAX_TBR70",
           "WELL_CONTROLLED_MAX_SEV54"]


def history_for(name, days=LOOKBACK_DAYS, seed=0, layers=None, profile=None,
                announcement="always"):
    """A subject's `V1Profile`, generated by running oref0 SMB for the same fortnight.

    A real profile is the person's own last fortnight on the previous version of the algorithm,
    which microboluses. A subject has none, so one is generated, and the generating loop has to
    microbolus or the derivation is fed a history it was not written for. The reference
    correction loop attaches its correction to the meal bolus rather than issuing it separately,
    so on one subject it produced 35 manual boluses with a ninetieth percentile of 13.85 U
    against a total daily dose of 31.2, and no microboluses at all, which drove the confirmed cap
    into its 7.5 U clamp and left the committed cap resting on total daily dose alone.

    oref0 SMB produces microboluses and is not the algorithm being configured, so the
    configuration is still not derived from the thing it configures.

    Every dose counts as a microbolus and the manual stream is left empty, which is correct for
    this algorithm rather than a shortcut. Boost detects meals and doses them itself, so a user
    of it does not enter boluses, and the simulator matches that: the person announces a meal or
    does not, and the algorithm decides everything. The derivation already handles an absent
    manual stream, since `MIN_MANUAL_BOLUS_SAMPLES` keeps a thin one out of the confirmed cap,
    and the cap then falls back to the microbolus ninety-fifth percentile alone. On these
    subjects that percentile is 0.90 U, so the cap sits at its 1.5 U floor. The committed cap,
    which sizes the routine per-cycle hold from the microbolus stream and total daily dose, lands
    near 1.1 U against a default of 0.25.
    """
    from ..simulation import run as run_mod
    from ..therapy import profile as profile_mod

    prof = profile or profile_mod.for_subject(name)
    layers = ("physiology", "behaviour", "sensor", "site") if layers is None else layers

    from . import oref as oref_mod

    seen = []
    ctrl = oref_mod.OrefController(name, profile=prof)
    base = type(ctrl).policy

    def traced(self, observation, reward, done, **info):
        action = base(self, observation, reward, done, **info)
        sample = float(info.get("sample_time", 5.0))
        seen.append((float(info.get("clock_minutes", 0.0)),
                     float(getattr(action, "bolus", 0.0)) * sample,
                     float(info.get("meal", 0.0)) * sample))
        return action

    type(ctrl).policy = traced
    try:
        r = run_mod.simulate(name, days=days, seed=seed, layers=layers,
                             controller=ctrl, profile=prof, announcement=announcement)
    finally:
        type(ctrl).policy = base
        ctrl.close()

    cgm = np.asarray(r.cgm, dtype=float)
    # No manual stream: this algorithm doses meals itself and its users do not enter boluses,
    # so every dose the loop gave is a microbolus whether or not carbohydrate was announced.
    manual = []
    smb = [b for _, b, _ in seen if b > 0]
    run_days = max(len(cgm) * float(r.sample_time) / 1440.0, 1e-9)
    return V1Profile(
        days_with_data=int(run_days),
        bg_reading_count=int(len(cgm)),
        tdd_median_u=float(r.insulin_units / run_days),
        manual_boluses_u=manual, smb_amounts_u=smb,
        tbr_below_70_pct=float(100.0 * np.mean(cgm < 70)),
        time_below_54_pct=float(100.0 * np.mean(cgm < 54)),
        mean_glucose_mgdl=float(np.mean(cgm)),
        current_max_iob_u=float(prof.limits.max_iob_u),
        current_max_bolus_u=float(prof.limits.max_bolus_u))


def configure(name, days=LOOKBACK_DAYS, seed=0, layers=None, profile=None,
              announcement="always"):
    """A subject's derived configuration, or None when its history is too thin.

    The history defaults to a fortnight in which every meal was announced, because that is the
    lineage a user onboards from: they arrive having been announcing, and the configuration is
    then carried unchanged into whatever they actually do.
    """
    return compute(history_for(name, days=days, seed=seed, layers=layers, profile=profile,
                               announcement=announcement))


__all__ += ["history_for", "configure"]
